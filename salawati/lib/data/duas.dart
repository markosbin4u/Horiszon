/// The supplications the app ships with, each tied to a moment of the Muslim's day or a
/// need. Arabic text only, with the occasion it belongs to.
library;

/// One supplication.
class Dua {
  const Dua({
    required this.id,
    required this.title,
    required this.text,
    required this.occasion,
    this.source,
  });

  final String id;

  /// A short name for the list: «دعاء الاستفتاح», «دعاء السفر».
  final String title;

  final String text;

  /// What it is for: «قبل الطعام», «عند الهم».
  final String occasion;

  /// Where it comes from: «متفق عليه», «صحيح مسلم».
  final String? source;
}

