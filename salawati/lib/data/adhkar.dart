/// The remembrance the app ships with. Text only, Arabic, as commonly recited; the app
/// keeps no generated or paraphrased wording.
library;

/// One dhikr: its text, how many times it is said, and its virtue or source.
class Dhikr {
  const Dhikr(this.text, {this.repeat = 1, this.note});

  final String text;
  final int repeat;
  final String? note;
}

/// One group of remembrance, as the app's list shows it.
